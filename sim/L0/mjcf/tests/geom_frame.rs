/// 0 on macOS arm64, where MuJoCo's values were printed, and 1e-12 of an
/// array's largest entry elsewhere, where the platform's libm gives other
/// last bits.
const TOLERANCE: f64 = if cfg!(all(target_os = "macos", target_arch = "aarch64")) {
    0.0
} else {
    1e-12
};

fn close(ours: &[f64], mujoco: &[f64]) -> bool {
    if ours.len() != mujoco.len() {
        return false;
    }
    if TOLERANCE == 0.0 {
        return ours
            .iter()
            .zip(mujoco)
            .all(|(a, b)| a.to_bits() == b.to_bits());
    }
    // Equal bits pass; otherwise both entries are finite and within the
    // tolerance of the array's largest finite entry, and two zeros have one
    // sign.
    let scale = mujoco
        .iter()
        .filter(|v| v.is_finite())
        .fold(0.0_f64, |m, v| m.max(v.abs()));
    ours.iter().zip(mujoco).all(|(a, b)| {
        a.to_bits() == b.to_bits()
            || (a.is_finite()
                && b.is_finite()
                && (a - b).abs() <= TOLERANCE * scale
                && !(*a == 0.0 && *b == 0.0))
    })
}

fn flat3(v: &[nalgebra::Vector3<f64>]) -> Vec<f64> {
    v.iter().flat_map(|x| x.iter().copied()).collect()
}

fn flat4(v: &[nalgebra::UnitQuaternion<f64>]) -> Vec<f64> {
    v.iter().flat_map(|q| [q.w, q.i, q.j, q.k]).collect()
}

/// Each document's geoms placed and bounded, its bodies' inertias and
/// bounding hierarchies made, its first `forward` and five steps, as MuJoCo
/// 3.5.0 composes a geom's frame.
#[test]
fn each_geoms_frame_composes_last_as_mujoco() {
    let mut wrong = Vec::new();
    for (doc, want) in CASES {
        let m = load_model(doc).unwrap();
        let mut d = m.make_data();
        d.forward(&m).unwrap();
        let (world, sensors) = (flat3(&d.geom_xpos), d.sensordata.as_slice().to_vec());
        for _ in 0..5 {
            d.step(&m).unwrap();
        }
        let differ: Vec<&str> = [
            (
                "geom_pos",
                close(&flat3(&m.geom_pos), want.geom_pos.as_flattened()),
            ),
            (
                "geom_quat",
                close(&flat4(&m.geom_quat), want.geom_quat.as_flattened()),
            ),
            (
                "geom_size",
                close(&flat3(&m.geom_size), want.geom_size.as_flattened()),
            ),
            (
                "geom_aabb",
                close(m.geom_aabb.as_flattened(), want.geom_aabb.as_flattened()),
            ),
            ("geom_rbound", close(&m.geom_rbound, want.geom_rbound)),
            (
                "site_pos",
                close(&flat3(&m.site_pos), want.site_pos.as_flattened()),
            ),
            (
                "site_quat",
                close(&flat4(&m.site_quat), want.site_quat.as_flattened()),
            ),
            ("body_mass", close(&m.body_mass, want.body_mass)),
            (
                "body_inertia",
                close(&flat3(&m.body_inertia), want.body_inertia.as_flattened()),
            ),
            (
                "body_ipos",
                close(&flat3(&m.body_ipos), want.body_ipos.as_flattened()),
            ),
            (
                "body_iquat",
                close(&flat4(&m.body_iquat), want.body_iquat.as_flattened()),
            ),
            (
                "bvh_aabb",
                close(m.bvh_aabb.as_flattened(), want.bvh_aabb.as_flattened()),
            ),
            ("geom_xpos", close(&world, want.geom_xpos.as_flattened())),
            ("sensordata", close(&sensors, want.sensordata)),
            ("qpos5", close(d.qpos.as_slice(), want.qpos5)),
        ]
        .into_iter()
        .filter(|&(_, same)| !same)
        .map(|(field, _)| field)
        .collect();
        if !differ.is_empty() {
            wrong.push(format!("{differ:?} differ: {doc}"));
        }
    }
    assert!(
        wrong.is_empty(),
        "{} of {}:\n{}",
        wrong.len(),
        CASES.len(),
        wrong.join("\n")
    );
}
