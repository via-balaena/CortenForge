#[test]
fn each_of_makes_checks_is_mujocos() {
    let mut missed = Vec::new();
    for (doc, reason) in single_faults() {
        match load_model(&doc) {
            Err(e) if e.to_string().contains(reason) => {}
            Err(e) => missed.push(format!("{doc}: {e} (MuJoCo: {reason})")),
            Ok(_) => missed.push(format!("{doc}: loads (MuJoCo: {reason})")),
        }
    }
    assert!(missed.is_empty(), "{}", missed.join("\n"));
}

#[test]
fn a_body_named_as_a_vertex_body_is_a_repeated_name_unless_the_point_is_pinned() {
    let unpinned = world(&format!(r#"<body name="f_0"/><flexcomp name="f" {G1}/>"#));
    let err = load_model(&unpinned).unwrap_err();
    assert!(err.to_string().contains("repeated name 'f_0'"), "{err}");
    // MuJoCo makes no body for a pinned point, and loads (measured: nbody 3).
    let pinned = world(&format!(
        r#"<body name="f_0"/><flexcomp name="f" {G1}><pin id="0"/></flexcomp>"#
    ));
    load_model(&pinned).unwrap();
}

