//! MuJoCo 3.5.0's body-level `<flexcomp>` (`mjCFlexcomp::Make`,
//! `user_flexcomp.cc:102-653`), made where the document writes it.
//!
//! Each `Expected` below is MuJoCo's model of the same document, measured on
//! the unfused oracle by `sim/L0/tests/scripts/gen_flexcomp_reference.py`,
//! whose output is the GENERATED section, as rustfmt lays it out. The bodies
//! MuJoCo makes are each document's first bodies here, in MuJoCo's order, and
//! every vertex's world position after a forward is MuJoCo's. A pinned point,
//! which MuJoCo puts on the body holding the flexcomp, is a jointless,
//! massless body of its own here, after MuJoCo's (registry
//! `D-FLEX-PINNED-BODY`).

// The GENERATED values are printed as Python's `repr` prints them, which
// round-trips each f64 exactly; separators would only be typed in by hand.
#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::unreadable_literal
)]

use sim_mjcf::{MjcfError, load_model};

/// MuJoCo's model of one document, as the generator prints it.
struct Expected {
    doc: &'static str,
    body_names: &'static [&'static str],
    body_parent: &'static [usize],
    body_pos: &'static [[f64; 3]],
    body_mass: &'static [f64],
    body_inertia: &'static [[f64; 3]],
    flex_names: &'static [&'static str],
    flex_rigid: &'static [bool],
    vertbody: &'static [usize],
    vert_xpos: &'static [[f64; 3]],
    elem: &'static [usize],
    edges: &'static [[usize; 2]],
    edge_rigid: &'static [bool],
    jnt_axis: &'static [[f64; 3]],
    dof_damping: &'static [f64],
    jnt_range: &'static [[f64; 2]],
    geom_size: &'static [f64],
    geom_group: &'static [i32],
    geom_contype: &'static [u32],
    neq: usize,
}

/// A loader value against MuJoCo's: equal on macOS arm64, where both run the
/// same libm; elsewhere within 1e-12 relative (a `NaN` fails either way).
// Exact on the one platform the golden's bits are from, by design.
#[allow(clippy::float_cmp)]
fn same(ours: f64, mujoco: f64) -> bool {
    if cfg!(all(target_os = "macos", target_arch = "aarch64")) {
        ours == mujoco
    } else {
        (ours - mujoco).abs() <= 1e-12 * (1.0 + mujoco.abs())
    }
}

fn same3(ours: [f64; 3], mujoco: [f64; 3]) -> bool {
    ours.iter().zip(mujoco).all(|(&a, b)| same(a, b))
}

/// Every difference between this crate's model of `e.doc` and MuJoCo's.
// A stand-in's mass is exactly 0 (it is written, not computed); one
// comparison per field, read top to bottom.
#[allow(clippy::float_cmp, clippy::too_many_lines)]
fn differences(what: &str, e: &Expected) -> Vec<String> {
    let model = match load_model(e.doc) {
        Ok(m) => m,
        Err(err) => return vec![format!("{what}: refused: {err}")],
    };
    let mut data = model.make_data();
    data.forward(&model).expect("forward");
    let mut out = Vec::new();
    let mut differ = |field: &str, ours: String, mujoco: String| {
        if ours != mujoco {
            out.push(format!("{what}: {field}: ours {ours}, MuJoCo {mujoco}"));
        }
    };
    let nb = e.body_names.len();
    differ(
        "nbody at least MuJoCo's",
        (model.nbody >= nb).to_string(),
        "true".into(),
    );
    let nb = nb.min(model.nbody);
    let names: Vec<&str> = (0..nb)
        .map(|b| model.body_name[b].as_deref().unwrap_or(""))
        .collect();
    differ(
        "body names",
        format!("{names:?}"),
        format!("{:?}", e.body_names),
    );
    differ(
        "body parents",
        format!("{:?}", &model.body_parent[..nb]),
        format!("{:?}", e.body_parent),
    );
    for b in 0..nb {
        let pos: [f64; 3] = model.body_pos[b].into();
        if !same3(pos, e.body_pos[b]) {
            differ(
                &format!("body {b} pos"),
                format!("{pos:?}"),
                format!("{:?}", e.body_pos[b]),
            );
        }
        if !same(model.body_mass[b], e.body_mass[b]) {
            differ(
                &format!("body {b} mass"),
                format!("{:?}", model.body_mass[b]),
                format!("{:?}", e.body_mass[b]),
            );
        }
        let inertia: [f64; 3] = model.body_inertia[b].into();
        if !same3(inertia, e.body_inertia[b]) {
            differ(
                &format!("body {b} inertia"),
                format!("{inertia:?}"),
                format!("{:?}", e.body_inertia[b]),
            );
        }
    }
    // A body past MuJoCo's is a pinned point's: jointless, massless, on the world.
    for b in nb..model.nbody {
        let stand_in =
            model.body_jnt_num[b] == 0 && model.body_parent[b] == 0 && model.body_mass[b] == 0.0;
        differ(
            &format!("body {b} a stand-in"),
            stand_in.to_string(),
            "true".into(),
        );
    }
    differ(
        "nflex",
        model.nflex.to_string(),
        e.flex_names.len().to_string(),
    );
    differ(
        "flex rigid",
        format!("{:?}", model.flex_rigid),
        format!("{:?}", e.flex_rigid),
    );
    differ(
        "nflexvert",
        model.nflexvert.to_string(),
        e.vertbody.len().to_string(),
    );
    for (v, &mj) in e.vertbody.iter().enumerate().take(model.nflexvert) {
        let ours = model.flexvert_bodyid[v];
        // MuJoCo's vertex body, or a stand-in where MuJoCo's is the holding body.
        let ok = ours == mj || (ours >= e.body_names.len() && model.body_jnt_num[ours] == 0);
        differ(&format!("vertex {v} body"), ok.to_string(), "true".into());
        let xpos: [f64; 3] = data.flexvert_xpos[v].into();
        if !same3(xpos, e.vert_xpos[v]) {
            differ(
                &format!("vertex {v} xpos"),
                format!("{xpos:?}"),
                format!("{:?}", e.vert_xpos[v]),
            );
        }
    }
    let mut elem = Vec::new();
    let mut edges = Vec::new();
    for f in 0..model.nflex {
        let base = model.flex_vertadr[f];
        for el in model.flex_elemadr[f]..model.flex_elemadr[f] + model.flex_elemnum[f] {
            let adr = model.flexelem_dataadr[el];
            for k in 0..model.flexelem_datanum[el] {
                elem.push(model.flexelem_data[adr + k] - base);
            }
        }
        for ed in model.flex_edgeadr[f]..model.flex_edgeadr[f] + model.flex_edgenum[f] {
            let [a, b] = model.flexedge_vert[ed];
            edges.push([a - base, b - base]);
        }
    }
    differ("elements", format!("{elem:?}"), format!("{:?}", e.elem));
    differ("edges", format!("{edges:?}"), format!("{:?}", e.edges));
    differ(
        "edges rigid",
        format!("{:?}", model.flexedge_rigid),
        format!("{:?}", e.edge_rigid),
    );
    let axes: Vec<[f64; 3]> = model.jnt_axis.iter().map(|&a| a.into()).collect();
    differ(
        "joint axes",
        format!("{axes:?}"),
        format!("{:?}", e.jnt_axis),
    );
    differ(
        "dof damping",
        format!("{:?}", model.dof_damping),
        format!("{:?}", e.dof_damping),
    );
    let ranges: Vec<[f64; 2]> = model.jnt_range.iter().map(|&r| r.into()).collect();
    differ(
        "joint ranges",
        format!("{ranges:?}"),
        format!("{:?}", e.jnt_range),
    );
    let sizes: Vec<f64> = model.geom_size.iter().map(|s| s.x).collect();
    differ(
        "geom sizes",
        format!("{sizes:?}"),
        format!("{:?}", e.geom_size),
    );
    differ(
        "geom groups",
        format!("{:?}", model.geom_group),
        format!("{:?}", e.geom_group),
    );
    differ(
        "geom contypes",
        format!("{:?}", model.geom_contype),
        format!("{:?}", e.geom_contype),
    );
    differ("neq", model.neq.to_string(), e.neq.to_string());
    out
}

fn assert_mujocos(cases: &[(&str, &Expected)]) {
    let all: Vec<String> = cases.iter().flat_map(|(w, e)| differences(w, e)).collect();
    assert!(all.is_empty(), "{}", all.join("\n"));
}

